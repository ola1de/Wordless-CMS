#!/usr/bin/env node
/**
 * Regenerate src/modules/themes/default-theme.ts from
 * themes/wordless-default/ (the source of truth).
 *
 * The Worker cannot read files at runtime, so the default theme ships as
 * an in-code bundle. This script is the only writer of that bundle;
 * themes.test.ts asserts the bundle matches the repo files byte for
 * byte (trimmed), so editing either side without regenerating fails
 * the test suite.
 *
 * Usage: node scripts/generate-default-theme.mjs
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const THEME_DIR = join(ROOT, "themes", "wordless-default");

function read(rel) {
  return readFileSync(join(THEME_DIR, rel), "utf8");
}

function listDir(rel) {
  return readdirSync(join(THEME_DIR, rel)).filter((f) => f.endsWith(".html"));
}

const themeJson = JSON.parse(read("theme.json"));
const templates = {};
for (const file of listDir("templates")) templates[`templates/${file}`] = read(`templates/${file}`);
const parts = {};
for (const file of listDir("parts")) parts[`parts/${file}`] = read(`parts/${file}`);
const styleCss = read("style.css");

const out = `/**
 * Built-in default theme (Milestone 5) — GENERATED, do not edit by hand.
 *
 * Generated by scripts/generate-default-theme.mjs from
 * themes/wordless-default/ (the source of truth). The Worker cannot read
 * files at runtime, so the default theme ships as this in-code bundle;
 * themes.test.ts asserts it matches the repo files byte for byte.
 * Original Wordless work — not a copy of any WordPress theme.
 */
export const DEFAULT_THEME_SLUG = "wordless-default";
export const DEFAULT_THEME_NAME = "Wordless";
export const DEFAULT_THEME_VERSION = "0.6.0";
export const DEFAULT_THEME_AUTHOR = "Wordless";

export const DEFAULT_THEME_JSON: Record<string, unknown> = ${JSON.stringify(themeJson, null, 2)};

export const DEFAULT_THEME_FILES: Record<string, string> = {
${Object.entries({ ...templates, ...parts })
  .map(([path, content]) => `  ${JSON.stringify(path)}: ${JSON.stringify(content)},`)
  .join("\n")}
};

export const DEFAULT_THEME_STYLE_CSS: string = ${JSON.stringify(styleCss)};
`;

writeFileSync(join(ROOT, "src", "modules", "themes", "default-theme.ts"), out);
console.log(
  `Wrote src/modules/themes/default-theme.ts (${Object.keys(templates).length} templates, ${Object.keys(parts).length} parts).`,
);
