/**
 * WordPress conversion engine (Milestone 4) — static analysis.
 *
 * `analyzePhp` walks a parsed program and summarises what a file does:
 * functions, classes, hooks, WordPress API calls, options, HTTP calls,
 * and the PHP features that decide convertibility. It never executes the
 * source. The Akismet report (docs/conversion/akismet-analysis.md) is
 * built from one FileAnalysis per PHP file.
 */
import { parsePhp } from "./parser";
import { walkAst } from "./ast";
import type { ExprNode } from "./ast";

export type Convertibility = "convertible" | "partial" | "blocked";

export interface UnconvertibleFeature {
  kind: string;
  reason: string;
  line: number;
}

export interface FileAnalysis {
  file: string;
  lines: number;
  bytes: number;
  tokens: number;
  nodes: number;
  functions: string[];
  classes: string[];
  hooks: { tag: string; kind: "action" | "filter" }[];
  wpCalls: string[];
  optionKeys: string[];
  httpCalls: string[];
  features: string[];
  unconvertible: UnconvertibleFeature[];
  verdict: Convertibility;
  reasons: string[];
}

const HTTP_CALLS = new Set([
  "wp_remote_get",
  "wp_remote_post",
  "wp_remote_request",
  "wp_remote_head",
  "wp_remote_retrieve_body",
  "wp_remote_retrieve_response_code",
  "wp_safe_remote_get",
  "wp_safe_remote_post",
  "wp_http_validate_url",
  "download_url",
]);

const OPTION_CALLS = new Set([
  "get_option",
  "update_option",
  "delete_option",
  "add_option",
  "get_site_option",
  "update_site_option",
]);

function literalString(node: ExprNode | undefined): string | null {
  if (node !== undefined && node.kind === "literal" && node.literalKind === "string") {
    return String(node.value);
  }
  return null;
}

/** Render the per-file analyses as the Akismet analysis markdown report. */
export function renderAnalysisReport(
  analyses: FileAnalysis[],
  opts: { title: string; intro: string; generatedBy: string },
): string {
  const totalLines = analyses.reduce((n, a) => n + a.lines, 0);
  const totalBytes = analyses.reduce((n, a) => n + a.bytes, 0);
  const byVerdict = (v: Convertibility): number => analyses.filter((a) => a.verdict === v).length;
  const lines: string[] = [];
  lines.push(`# ${opts.title}`);
  lines.push(``);
  lines.push(opts.intro);
  lines.push(``);
  lines.push(`Generated by the Wordless conversion engine (Milestone 4) static analysis.`);
  lines.push(`No PHP was executed; every file below was parsed, not run.`);
  lines.push(``);
  lines.push(`## Summary`);
  lines.push(``);
  lines.push(`- Files analysed: **${analyses.length}**`);
  lines.push(`- Total lines: **${totalLines}** · total size: **${(totalBytes / 1024).toFixed(1)} KB**`);
  lines.push(`- Convertible: **${byVerdict("convertible")}** · Partial: **${byVerdict("partial")}** · Blocked: **${byVerdict("blocked")}**`);
  lines.push(``);
  lines.push(`| File | Lines | Verdict | Why |`);
  lines.push(`| --- | ---: | --- | --- |`);
  for (const a of analyses) {
    lines.push(`| \`${a.file}\` | ${a.lines} | ${a.verdict} | ${a.reasons.join(" ")} |`);
  }
  lines.push(``);
  for (const a of analyses) {
    lines.push(`## \`${a.file}\` — ${a.verdict}`);
    lines.push(``);
    lines.push(`- Lines: ${a.lines} · bytes: ${a.bytes} · tokens: ${a.tokens} · AST nodes: ${a.nodes}`);
    if (a.functions.length > 0) lines.push(`- Functions: ${a.functions.join(", ")}`);
    if (a.classes.length > 0) lines.push(`- Classes: ${a.classes.join(", ")}`);
    if (a.hooks.length > 0) {
      lines.push(`- Hooks: ${a.hooks.map((h) => `${h.kind} "${h.tag}"`).join(", ")}`);
    }
    if (a.wpCalls.length > 0) lines.push(`- WordPress APIs used: ${a.wpCalls.join(", ")}`);
    if (a.optionKeys.length > 0) lines.push(`- Options used: ${a.optionKeys.join(", ")}`);
    if (a.httpCalls.length > 0) lines.push(`- HTTP calls: ${a.httpCalls.join(", ")}`);
    if (a.features.length > 0) lines.push(`- PHP features: ${a.features.join(", ")}`);
    if (a.unconvertible.length > 0) {
      lines.push(`- Needs manual work (${a.unconvertible.length}):`);
      for (const u of a.unconvertible.slice(0, 12)) {
        lines.push(`  - line ${u.line}: ${u.kind} — ${u.reason}`);
      }
      if (a.unconvertible.length > 12) {
        lines.push(`  - … and ${a.unconvertible.length - 12} more (same kinds).`);
      }
    }
    lines.push(`- Verdict: **${a.verdict}** — ${a.reasons.join(" ")}`);
    lines.push(``);
  }
  lines.push(`---`);
  lines.push(``);
  lines.push(`## Effort estimate (honest, not a promise)`);
  lines.push(``);
  const totalUnconvertible = analyses.reduce((n, a) => n + a.unconvertible.length, 0);
  const classCount = analyses.reduce((n, a) => n + a.classes.length, 0);
  const httpFiles = analyses.filter((a) => a.httpCalls.length > 0).length;
  const wpdbFiles = analyses.filter((a) => a.features.includes("$wpdb")).length;
  const convertibleLines = analyses.filter((a) => a.verdict === "convertible").reduce((n, a) => n + a.lines, 0);
  lines.push(`- **Convertible files (${byVerdict("convertible")}, ${convertibleLines} lines):** under a day of review — run the converter, read the output, enable.`);
  lines.push(`- **Partial files (${byVerdict("partial")}):** blocked on a class runtime Wordless does not have yet (M4 analyses classes, it does not convert them). Building one is a milestone-scale job in its own right (est. 2–4 weeks of focused work), after which these files still need their ${totalUnconvertible} flagged items reviewed one by one.`);
  lines.push(`- **Blocked files (${byVerdict("blocked")}):** ${httpFiles} file${httpFiles === 1 ? "" : "s"} call an external HTTP API and ${wpdbFiles} file${wpdbFiles === 1 ? "" : "s"} use $wpdb. Neither is a translation problem: the API calls need a service integration (Phase 8) and the spam decision itself needs the Akismet service and its spam database. That is the real work, and it is commercial (API key, account, rate limits) — not something a converter can supply.`);
  lines.push(`- **Bottom line:** a faithful Akismet port is a multi-week project plus a commercial API integration, not a conversion run. The M4 engine's honest contribution is this map: 9 files are nearly free, ${classCount} classes need a runtime, and 4 files need an integration that no amount of translation replaces.`);
  lines.push(``);
  lines.push(opts.generatedBy);
  return lines.join("\n");
}
export function analyzePhp(source: string, filename: string): FileAnalysis {
  const { program, tokens } = parsePhp(source);
  const lines = source.split("\n").length;
  const bytes = new TextEncoder().encode(source).length;

  const functions: string[] = [];
  const classes: string[] = [];
  const hooks: { tag: string; kind: "action" | "filter" }[] = [];
  const wpCalls = new Set<string>();
  const optionKeys = new Set<string>();
  const httpCalls = new Set<string>();
  const features = new Set<string>();
  const unconvertible: UnconvertibleFeature[] = [];
  let nodeCount = 0;

  // The ABSPATH direct-access guard is transformed by the emitter (not
  // unconverted): collect the guarded exit/die lines so they are not
  // counted as manual work. Same check as the emitter's isAbpsathGuard.
  const guardLines = new Set<number>();
  walkAst(program, (node) => {
    if (node.kind !== "if") return;
    const test = node.test;
    if (test.kind !== "unary" || test.operator !== "!") return;
    const inner = test.operand;
    if (inner.kind !== "call" || inner.name?.toLowerCase() !== "defined") return;
    const arg = inner.args[0];
    if (arg === undefined || arg.kind !== "literal" || arg.literalKind !== "string") return;
    if (String(arg.value) !== "ABSPATH") return;
    if (!node.consequent.every((s) => s.kind === "unsupported" && (s.label === "exit()" || s.label === "die()"))) {
      return;
    }
    for (const s of node.consequent) guardLines.add(s.pos.line);
  });

  walkAst(program, (node) => {
    nodeCount++;
    switch (node.kind) {
      case "function":
        functions.push(node.name);
        break;
      case "class":
        classes.push(node.name);
        features.add("class");
        unconvertible.push({
          kind: "class",
          reason: `Class ${node.name} (${node.methods.length} methods) needs a class runtime, which Wordless does not provide yet.`,
          line: node.pos.line,
        });
        break;
      case "method":
        features.add("method");
        break;
      case "closure":
        features.add("closure");
        if (node.uses.length > 0) features.add("closure-use");
        break;
      case "new":
        features.add("new");
        unconvertible.push({
          kind: "instantiation",
          reason: `new ${node.className}() needs a class runtime.`,
          line: node.pos.line,
        });
        break;
      case "method_call":
        features.add("method-call");
        break;
      case "static_call":
        features.add("static-call");
        break;
      case "property_fetch":
        features.add("property-fetch");
        break;
      case "switch":
        features.add("switch");
        if (node.altSyntax === true) features.add("alternative-syntax");
        unconvertible.push({
          kind: "switch",
          reason: "switch statements are not translated yet; rewrite as if/else.",
          line: node.pos.line,
        });
        break;
      case "try":
        features.add("try-catch");
        break;
      case "foreach":
        features.add("foreach");
        if (node.altSyntax === true) features.add("alternative-syntax");
        break;
      case "for":
        features.add("for");
        if (node.altSyntax === true) features.add("alternative-syntax");
        break;
      case "while":
        features.add("while");
        if (node.altSyntax === true) features.add("alternative-syntax");
        break;
      case "if":
        if (node.altSyntax === true) features.add("alternative-syntax");
        break;
      case "cast":
        features.add("cast");
        break;
      case "static_var":
        features.add("static-var");
        break;
      case "do_while":
        features.add("do-while");
        break;
      case "global":
        features.add("global");
        unconvertible.push({
          kind: "global",
          reason: "global variables have no equivalent in Wordless extensions.",
          line: node.pos.line,
        });
        break;
      case "inline_html":
        features.add("inline-html");
        break;
      case "unsupported":
        // The ABSPATH guard's exit/die is transformed, not manual work.
        if (guardLines.has(node.pos.line)) break;
        unconvertible.push({ kind: node.label, reason: node.reason, line: node.pos.line });
        break;
      case "unsupported_expr":
        unconvertible.push({ kind: node.label, reason: node.reason, line: node.pos.line });
        break;
      case "call": {
        const name = node.name;
        if (name === null) {
          features.add("dynamic-call");
          break;
        }
        const lower = name.toLowerCase();
        if (lower === "add_action" || lower === "add_filter") {
          const tag = literalString(node.args[0]);
          if (tag !== null) hooks.push({ tag, kind: lower === "add_action" ? "action" : "filter" });
        }
        if (OPTION_CALLS.has(lower)) {
          const key = literalString(node.args[0]);
          if (key !== null) optionKeys.add(key);
        }
        if (HTTP_CALLS.has(lower)) httpCalls.add(lower);
        if (lower.startsWith("wp_") || lower.startsWith("get_") || lower.startsWith("update_") || lower.startsWith("delete_") || lower.startsWith("add_") || lower === "__" || lower === "_e" || lower.startsWith("esc_") || lower === "apply_filters" || lower === "do_action") {
          wpCalls.add(lower);
        }
        if (lower === "eval" || lower === "exec" || lower === "shell_exec" || lower === "system" || lower === "passthru" || lower === "create_function" || lower === "unserialize") {
          features.add("blocked-construct");
          unconvertible.push({
            kind: lower,
            reason: `${lower}() is blocked by the conversion sandbox.`,
            line: node.pos.line,
          });
        }
        break;
      }
      case "var": {
        if (node.name === "this") features.add("$this");
        if (
          ["_GET", "_POST", "_SERVER", "_FILES", "_COOKIE", "_REQUEST", "_SESSION", "GLOBALS"].includes(node.name)
        ) {
          features.add("superglobal");
        }
        break;
      }
      default:
        break;
    }
  });

  // $wpdb usage shows up as a variable named wpdb.
  if (/\$wpdb\b/.test(source)) {
    features.add("$wpdb");
    unconvertible.push({
      kind: "$wpdb",
      reason: "Direct database access via $wpdb is not available to Wordless extensions; use the wp API (get_post, get_option, …).",
      line: 1,
    });
  }
  if (/\bnamespace\b/.test(source)) features.add("namespace");
  if (/\bheredoc\b/i.test(source)) features.add("heredoc");

  const reasons: string[] = [];
  let verdict: Convertibility = "convertible";
  const blockedByExternal =
    httpCalls.size > 0 ||
    features.has("$wpdb") ||
    features.has("blocked-construct");
  const hasClasses = classes.length > 0;
  if (blockedByExternal) {
    verdict = "blocked";
    if (httpCalls.size > 0) reasons.push(`calls an external HTTP API (${[...httpCalls].join(", ")}), which needs a service integration, not a translation.`);
    if (features.has("$wpdb")) reasons.push("uses $wpdb for direct database access.");
    if (features.has("blocked-construct")) reasons.push("contains a construct blocked by the conversion sandbox.");
  } else if (hasClasses || unconvertible.length > 0) {
    verdict = "partial";
    if (hasClasses) reasons.push(`defines ${classes.length} class${classes.length === 1 ? "" : "es"} (${classes.join(", ")}); classes are analysed but not converted.`);
    if (unconvertible.length > 0 && !hasClasses) {
      reasons.push(`${unconvertible.length} construct${unconvertible.length === 1 ? "" : "s"} need${unconvertible.length === 1 ? "s" : ""} manual work.`);
    }
  } else {
    reasons.push("procedural code using only mapped or mappable WordPress APIs.");
  }

  return {
    file: filename,
    lines,
    bytes,
    tokens: tokens.length,
    nodes: nodeCount,
    functions,
    classes,
    hooks,
    wpCalls: [...wpCalls].sort(),
    optionKeys: [...optionKeys].sort(),
    httpCalls: [...httpCalls].sort(),
    features: [...features].sort(),
    unconvertible,
    verdict,
    reasons,
  };
}
